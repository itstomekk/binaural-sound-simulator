"""Encode assets/voices/_wav/*.wav to padded mono mp3 and emit src/voices.generated.js (base64)."""
import base64, json, subprocess, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
wav = root / "assets/voices/_wav"; mp3 = root / "assets/voices"
labels = {
  "front": "Voice: “Front”", "behind": "Voice: “Behind”", "above": "Voice: “Above”",
  "below": "Voice: “Below”", "left": "Voice: “Left”", "right": "Voice: “Right”",
  "hello-en": "Voice: Hello (English)", "hello-pl": "Voice: Cześć Tomek (Polski)",
}
out = []
for name, label in labels.items():
    dst = mp3 / f"{name}.mp3"
    pad = ["-af", "apad=whole_dur=2.7"] if name not in ("hello-en", "hello-pl") else ["-af", "apad=pad_dur=1.2"]
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav / f"{name}.wav"), *pad,
                    "-ac", "1", "-ar", "24000", "-b:a", "40k", str(dst)], check=True)
    out.append({"id": f"voice-{name}", "label": label, "mp3": base64.b64encode(dst.read_bytes()).decode()})
(root / "src/voices.generated.js").write_text(
    "// GENERATED by tools/build_voices.py — do not edit\nexport const VOICES = " + json.dumps(out, ensure_ascii=False) + ";\n", encoding="utf-8")
print(len(out), "voices;", sum(len(o["mp3"]) for o in out)//1024, "KB base64")
